const isSupported = (value: string): value is AuthLocale =>
  (SUPPORTED_LOCALES as readonly string[]).includes(value)

/**
 * Picks the best supported locale for an explicit BCP-47 tag (or a list, most preferred first),
 * then from `navigator.languages`, then English. Regional tags (`zh-TW`, `de-AT`) match their base language.
 */
export function resolveLocale(preferred?: string | readonly string[]): AuthLocale {
  const candidates: string[] = [
    ...(preferred ? ([] as string[]).concat(preferred as string | string[]) : []),
    ...(typeof navigator !== 'undefined'
      ? [...(navigator.languages ?? []), navigator.language]
      : [])
  ]
  for (const tag of candidates) {
    const base = tag?.toLowerCase().split(/[-_]/)[0]
    if (base && isSupported(base)) return base
  }
  return 'en'
}

/** Replaces `{name}` placeholders. */
export function format(template: string, vars: Record<string, string | number> = {}): string {
  return template.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m))
}
